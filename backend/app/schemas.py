# --- Budget -----------------------------------------------------------------


class BudgetLineIn(BaseModel):
    partida_code: str
    partida_name: str | None = None
    approved_donor: Decimal | None = None
    approved_total: Decimal | None = None
    executed_donor: Decimal | None = None
    executed_total: Decimal | None = None
    # False for subtotal/aggregate rows (TOTAL..., % SOBRE TOTALES...). For "PCT_*" rows the
    # amount fields hold ratios, not euros.
    is_partida: bool = True


class BudgetLineOut(OrmModel, BudgetLineIn):
    id: int
    project_id: int


# --- Expense ----------------------------------------------------------------


class ExpenseIn(BaseModel):
    order_no: str | None = None
    order_key: str | None = None
    date: dt.date | None = None
    source: str | None = None
    issuer: str | None = None
    concept: str | None = None
    partida_code: str | None = None
    partida_raw: str | None = None
    amount_local: Decimal | None = None
    currency: str | None = None
    fx_rate: Decimal | None = None
    amount_eur: Decimal | None = None
    amount_donor: Decimal | None = None
    source_row: int | None = None
    # Donor-specific extras, e.g. {"invoice_no": "...", "payment": "...", "other_funders": {...}}.
    extra: dict[str, Any] | None = None

    @field_serializer("extra", when_used="always")
    def _json_safe_extra(self, extra: dict[str, Any] | None) -> dict[str, Any] | None:
        """`extra` is stored as JSONB: Decimals become numbers, dates ISO strings."""
        return None if extra is None else _json_safe(extra)


class ExpenseOut(OrmModel, ExpenseIn):
    id: int
    project_id: int
    suggested_partida: str | None = None
    suggested_confidence: float | None = None
    suggested_reason: str | None = None


