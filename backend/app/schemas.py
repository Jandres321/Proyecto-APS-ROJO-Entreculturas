# --- Donor catalog (returned by adapters, not stored as-is) ------------------


class Partida(BaseModel):
    """Budget line definition from the donor's rules, used to classify expenses."""

    code: str
    name: str
    definition: str = ""
    includes: list[str] = Field(default_factory=list)
    excludes: list[str] = Field(default_factory=list)
    # Where the definition comes from (guide section / article), shown in explanations.
    reference: str = ""


class LimitBase(StrEnum):
    """What `max_pct` is a fraction of."""

    DONOR_GRANT = "donor_grant"  # approved donor subsidy (AECID)
    PROJECT_TOTAL = "project_total"  # total project budget (Xunta)


class LimitScope(StrEnum):
    BUDGET = "budget"  # cap on the sum of the partidas, checked on the budget execution
    EXPENSE = "expense"  # threshold for a single expense (e.g. 3 offers above 15.000 EUR)


class Limit(BaseModel):
    """Donor cap (checked in code, never by the LLM).

    scope=budget: the sum of `partida_codes` must not exceed `max_pct` (fraction 0-1 of
    `base`) and/or `max_amount_eur`.
    scope=expense: `max_amount_eur` is the amount of ONE expense above which the rule in
    `description` applies; empty `partida_codes` means every partida.
    """

    code: str
    description: str
    partida_codes: list[str] = Field(default_factory=list)
    scope: LimitScope = LimitScope.BUDGET
    base: LimitBase = LimitBase.DONOR_GRANT
    max_pct: Decimal | None = None
    max_amount_eur: Decimal | None = None
    reference: str | None = None
    severity: Severity = Severity.HIGH
